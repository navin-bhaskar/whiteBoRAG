"""Write whiteborag_cam/secrets.h from Terraform outputs and Wi-Fi credentials.

    python ESP32-cam/firmware/tools/gen_secrets.py --wifi-from ESP32-cam/testing/snap_upload_s3/config.h

API_BASE_URL and API_KEY come from `terraform -chdir=infra output -json`.
Wi-Fi credentials come from --wifi-from (a header with WIFI_SSID and
WIFI_PASSWORD #defines) or else the WIFI_SSID / WIFI_PASSWORD environment
variables. secrets.h is git-ignored, and nothing secret is printed.
"""

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
DEFAULT_OUT = ROOT / "ESP32-cam" / "firmware" / "whiteborag_cam" / "secrets.h"


def c_string(value):
    return json.dumps(value, ensure_ascii=False)  # JSON escapes are valid C escapes


def wifi_literals(header):
    """Returns the (SSID, password) C string literals from a header, as written."""
    if header is None:
        try:
            return c_string(os.environ["WIFI_SSID"]), c_string(os.environ["WIFI_PASSWORD"])
        except KeyError:
            sys.exit("pass --wifi-from or set WIFI_SSID and WIFI_PASSWORD")
    text = header.read_text(encoding="utf-8")
    found = {}
    for name in ("WIFI_SSID", "WIFI_PASSWORD"):
        m = re.search(rf'^\s*#define\s+{name}\s+("(?:[^"\\]|\\.)*")', text, re.M)
        if not m:
            sys.exit(f"{name} not found in {header}")
        found[name] = m.group(1)
    return found["WIFI_SSID"], found["WIFI_PASSWORD"]


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--wifi-from", type=Path)
    p.add_argument("--device", default="wb-cam-01")
    p.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = p.parse_args()

    out = subprocess.run(
        ["terraform", f"-chdir={ROOT / 'infra'}", "output", "-json"],
        check=True, capture_output=True, text=True,
    ).stdout
    outputs = json.loads(out)
    base_url = outputs["api_base_url"]["value"]
    keys = outputs["api_keys"]["value"]
    if args.device not in keys:
        sys.exit(f"no API key for {args.device}; Terraform has: {', '.join(sorted(keys))}")

    ssid, password = wifi_literals(args.wifi_from)
    args.out.write_text(
        "#pragma once\n\n"
        "// Generated by tools/gen_secrets.py. Git-ignored: never commit this file.\n"
        f"#define WIFI_SSID     {ssid}\n"
        f"#define WIFI_PASSWORD {password}\n"
        f"#define API_BASE_URL  {c_string(base_url)}\n"
        f"#define API_KEY       {c_string(keys[args.device])}\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"wrote {args.out} for {args.device} ({base_url})")


if __name__ == "__main__":
    main()
