"""Regenerate whiteborag_cam/certs.h, the TLS trust anchors for the firmware.

    python ESP32-cam/firmware/tools/gen_certs.py

API Gateway (*.execute-api.ap-south-1) and S3 (*.s3.ap-south-1) both chain to
Amazon Root CA 1, which is cross-signed by Starfield Services Root CA G2, so
either root verifies both. The PEMs are downloaded from amazontrust.com and
nothing is written unless each SHA-256 fingerprint matches the pinned value.
"""

import argparse
import hashlib
import ssl
import sys
import urllib.request
from pathlib import Path

DEFAULT_OUT = Path(__file__).resolve().parents[1] / "whiteborag_cam" / "certs.h"

ROOTS = [
    (
        "Amazon Root CA 1 (expires 2038-01-17)",
        "https://www.amazontrust.com/repository/AmazonRootCA1.pem",
        "8ecde6884f3d87b1125ba31ac3fcb13d7016de7f57cc904fe1cb97c6ae98196e",
    ),
    (
        "Starfield Services Root CA G2 (expires 2037-12-31)",
        "https://www.amazontrust.com/repository/SFSRootCAG2.pem",
        "568d6905a2c88708a4b3025190edcfedb1974a606a13c6e5290fcb2ae63edab5",
    ),
]


def fetch(name, url, pinned):
    with urllib.request.urlopen(url, timeout=15) as resp:
        pem = resp.read().decode("ascii").strip()
    got = hashlib.sha256(ssl.PEM_cert_to_DER_cert(pem)).hexdigest()
    if got != pinned:
        sys.exit(f"{name}: SHA-256 {got} does not match pinned {pinned}; not writing")
    return pem


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = p.parse_args()

    lines = [
        "#pragma once",
        "",
        "// Generated by tools/gen_certs.py; do not edit by hand.",
        "// API Gateway and S3 in ap-south-1 both chain to Amazon Root CA 1, which is",
        "// cross-signed by Starfield Services Root CA G2. Either root verifies both.",
        "static const char ROOT_CA_BUNDLE[] =",
    ]
    for name, url, pinned in ROOTS:
        lines.append(f"    // {name}")
        lines += [f'    "{line}\\n"' for line in fetch(name, url, pinned).splitlines()]
    lines[-1] += ";"

    args.out.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
